"""Bounded raw SEC HTML adapter for Apple's FY2024 10-K, not a generic SEC parser.

Numeric values are read from original cells, never from evaluation answers.
The raw document hash is pinned; extract_html is also exercised with corrupted
HTML in tests. Production parse_html always checks source identity first.
"""
import hashlib
import json
import re
from datetime import date
from pathlib import Path
from lxml import html
from .store import ROOT

DOCUMENT_ID='apple-2024-10k'
URL='https://www.sec.gov/Archives/edgar/data/320193/000032019324000123/aapl-20240928.htm'
SHA='5699ae3d9c78d05cef529647ecb478b73f7b4616e37ae80dccef3a51c5837469'
TITLE='Apple FY2024 Form 10-K · 2024·2023 연결재무제표'
DATA=ROOT/'data/apple-source'
PERIODS={2024:('2023-10-01','2024-09-28',52),2023:('2022-09-25','2023-09-30',53)}
# Original row labels, section, printed page, taxonomy and dimensions form the
# adapter contract. No gold amounts or user questions are used by extraction.
SPECS=[
 ('products_sales',29,'Net sales','Products','us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax','us-gaap:ProductMember'),
 ('services_sales',29,'Net sales','Services','us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax','us-gaap:ServiceMember'),
 ('products_cost',29,'Cost of sales','Products','us-gaap:CostOfGoodsAndServicesSold','us-gaap:ProductMember'),
 ('services_cost',29,'Cost of sales','Services','us-gaap:CostOfGoodsAndServicesSold','us-gaap:ServiceMember'),
 ('operating_profit',29,None,'Operating income','us-gaap:OperatingIncomeLoss',None),
 ('tax_expense',29,None,'Provision for income taxes','us-gaap:IncomeTaxExpenseBenefit',None),
 ('net_income',29,None,'Net income','us-gaap:NetIncomeLoss',None),
 ('china_sales',22,None,'Greater China',None,None),
 ('total_sales',22,None,'Total net sales',None,None),
 ('operating_cash',33,None,'Cash generated by operating activities','us-gaap:NetCashProvidedByUsedInOperatingActivities',None),
 ('capex_payment',33,None,'Payments for acquisition of property, plant and equipment','us-gaap:PaymentsToAcquirePropertyPlantAndEquipment',None),
 ('buyback_payment',33,None,'Repurchases of common stock','us-gaap:PaymentsForRepurchaseOfCommonStock',None),
 ('state_aid_tax',40,None,'Impact of the State Aid Decision','aapl:EffectiveIncomeTaxRateReconciliationImpactOfTheStateAidDecisionAmount',None),
]
TITLES={22:'Net sales by reportable segment',29:'Consolidated Statements of Operations',33:'Consolidated Statements of Cash Flows',40:'Income tax reconciliation'}

def norm(e):return ' '.join(e.text_content().split())
def require(condition,code):
    if not condition:raise ValueError(code)
def printed_page(table):
    for e in table.xpath('following::div'):
        m=re.fullmatch(r'Apple Inc\. \| 2024 Form 10-K \| (\d+)',norm(e))
        if m:return int(m[1])
    return None

def spans(row):
    offset=0
    for td in row.xpath('./td|./th'):
        require('rowspan' not in td.attrib,'UNSUPPORTED_ROWSPAN')
        width=int(td.attrib.get('colspan','1'));require(0<width<100,'INVALID_COLSPAN')
        yield offset,offset+width,td
        offset+=width

def year_spans(table):
    candidates=[]
    for tr in table.xpath('./tr|./tbody/tr'):
        found={}
        for start,end,td in spans(tr):
            text=norm(td)
            m=re.fullmatch(r'(?:(?:September \d{2},)\s*)?(202[234])',text)
            if m:
                y=int(m[1]);require(y not in found,'DUPLICATE_YEAR_HEADER');found[y]=(start,end)
        if 2024 in found and 2023 in found:candidates.append(found)
    require(len(candidates)==1,'AMBIGUOUS_YEAR_HEADER')
    return candidates[0]

def extract_html(raw):
    """Structural parser; unpinned callers are mutation/fixture tests only."""
    root=html.fromstring(raw,parser=html.HTMLParser(no_network=True))
    tree=root.getroottree();full=norm(root)
    require('Apple Inc.' in full and '2024 Form 10-K' in full,'DOCUMENT_IDENTITY')
    require('dollars in millions' in full,'DOCUMENT_UNIT')
    contexts={};units={}
    for e in root.iter():
        if e.tag in ('xbrli:context','xbrli:unit'):
            target=contexts if e.tag=='xbrli:context' else units
            require(e.attrib['id'] not in target,'DUPLICATE_XBRL_ID')
            target[e.attrib['id']]=e
    tables={}
    # Match table by original labels and printed page, not by a global index.
    for page in TITLES:
        labels={s[3] for s in SPECS if s[1]==page}
        matched=[]
        for t in root.xpath('//table'):
            rows={norm(tr.xpath('./td|./th')[0]) for tr in t.xpath('./tr|./tbody/tr') if tr.xpath('./td|./th')}
            if labels<=rows and printed_page(t)==page:matched.append(t)
        require(len(matched)==1,'AMBIGUOUS_SOURCE_TABLE')
        tables[page]=matched[0]
    cells=[]
    for metric,page,group,label,taxonomy,dimension in SPECS:
        t=tables[page];headers=year_spans(t);section=None;matches=[]
        for tr in t.xpath('./tr|./tbody/tr'):
            tds=tr.xpath('./td|./th')
            if not tds:continue
            first=norm(tds[0])
            if first.endswith(':'):section=first.rstrip(':')
            if first==label and (group is None or section==group):matches.append(tr)
        require(len(matches)==1,'AMBIGUOUS_SOURCE_ROW')
        for year in ((2024,) if metric=='state_aid_tax' else (2024,2023)):
            start,end,weeks=PERIODS[year];lo,hi=headers[year];selected=[]
            for a,b,td in spans(matches[0]):
                if lo<=a<hi and re.fullmatch(r'\(?[0-9,]+\)?',norm(td)):selected.append(td)
            require(len(selected)==1,'AMBIGUOUS_AMOUNT_COLUMN')
            td=selected[0];raw_value=norm(td)
            value=raw_value.replace(',','').replace('(','-').replace(')','')
            require(re.fullmatch(r'-?\d+',value) is not None,'INVALID_SOURCE_NUMBER')
            facts=list(td.iter('ix:nonfraction'));fact=None;context_ref=None
            if taxonomy:
                require(len(facts)==1,'AMBIGUOUS_XBRL_FACT');fact=facts[0]
                require(fact.attrib['name']==taxonomy,'XBRL_ACCOUNT_MISMATCH')
                require(fact.attrib.get('scale')=='6' and norm(units[fact.attrib['unitref']])=='iso4217:USD','XBRL_UNIT_MISMATCH')
                context_ref=fact.attrib['contextref'];ctx=contexts[context_ref]
                def texts(tag):return [x.text for x in ctx.iter(tag)]
                require(texts('xbrli:identifier')==['0000320193'],'XBRL_COMPANY_MISMATCH')
                require(texts('xbrli:startdate')==[start] and texts('xbrli:enddate')==[end],'XBRL_PERIOD_MISMATCH')
                dims=[(x.attrib.get('dimension'),x.text) for x in ctx.iter('xbrldi:explicitmember')]
                require(dims==([('srt:ProductOrServiceAxis',dimension)] if dimension else []),'XBRL_DIMENSION_MISMATCH')
                require(not list(ctx.iter('xbrldi:typedmember')),'XBRL_DIMENSION_MISMATCH')
                require(fact.attrib.get('format')=='ixt:num-dot-decimal','XBRL_NUMBER_FORMAT')
                require(fact.attrib.get('sign') in (None,'-'),'XBRL_SIGN_MISMATCH')
                if fact.attrib.get('sign')=='-':require(value.startswith('-'),'XBRL_SIGN_MISMATCH')
                require(norm(fact).replace(',','')==value.lstrip('-'),'XBRL_DISPLAY_MISMATCH')
            else:require(not facts,'UNEXPECTED_XBRL_STRUCTURE')
            outflow=metric in ('capex_payment','buyback_payment')
            if outflow:require(value.startswith('-'),'CASH_OUTFLOW_SIGN_REQUIRED')
            fact_id=fact.attrib.get('id') if fact is not None else None
            cells.append({'id':f'{DOCUMENT_ID}:{metric}:{year}','document_id':DOCUMENT_ID,
                'document_sha256':SHA,'source_url':URL,'source_format':'SEC_HTML',
                'company':'apple','scope':'CFS','currency':'USD','scale':1000000,
                'metric':metric,'value':value,'raw_value':raw_value,'year':year,
                'period_kind':'duration','as_of':None,'start':start,'end':end,'fiscal_weeks':weeks,
                'page':None,'printed_page':page,'table_id':f'apple-p{page}','table_title':TITLES[page],
                'section':group,'row':label,'column':str(year),'amount_column':1 if year==2024 else 2,
                'row_role':'cash_outflow' if outflow else 'labelled',
                'table_xpath':tree.getpath(t),'cell_xpath':tree.getpath(td),'logical_column_span':[lo,hi],
                'xbrl_name':taxonomy,'context_ref':context_ref,'fact_id':fact_id,
                'source_locator':f'#{fact_id}' if fact_id else '',
                'unit_basis':'USD inline XBRL scale=6' if taxonomy else 'regional table introduction: dollars in millions'})
    narratives=[]
    for key,needle,page in [('fiscal_weeks','The Company’s fiscal years 2024 and 2022 spanned 52 weeks each',34),('china_drivers','Greater China net sales decreased during 2024 compared to 2023 due primarily to',22)]:
        found=[e for e in root.xpath('//span') if needle in norm(e) and printed_page(e)==page and not any(needle in norm(c) for c in e)]
        require(len(found)==1,'AMBIGUOUS_NARRATIVE')
        e=found[0];p=printed_page(e)
        require(p==page,'NARRATIVE_PAGE_MISMATCH')
        narratives.append({'id':f'{DOCUMENT_ID}:text:{key}','document_id':DOCUMENT_ID,'document_sha256':SHA,
            'source_url':URL,'source_format':'SEC_HTML','printed_page':p,'page':None,'text':norm(e),'xpath':tree.getpath(e),'key':key})
    require(len(cells)==25 and len({c['id'] for c in cells})==25,'SOURCE_CELL_COUNT')
    return {'cells':cells,'narratives':narratives}

def parse_html(path):
    raw=Path(path).read_bytes()
    require(hashlib.sha256(raw).hexdigest()==SHA,'UNSUPPORTED_HTML_HASH')
    return extract_html(raw)

def load_source():
    m=json.loads((DATA/'manifest.json').read_text());raw=(DATA/'evidence.json').read_bytes()
    require(m['id']==DOCUMENT_ID and m['sha256']==SHA and hashlib.sha256(raw).hexdigest()==m['evidence_sha256'],'SOURCE_EVIDENCE_INTEGRITY')
    e=json.loads(raw)
    require(len(e['cells'])==25 and len({c['id'] for c in e['cells']})==25,'SOURCE_CELL_COUNT')
    return m,e

def get_cell(cell_id):
    for c in load_source()[1]['cells']:
        if c['id']==cell_id:return c
    raise ValueError('UNKNOWN_SOURCE_CELL')
